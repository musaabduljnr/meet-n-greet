/**
 * Returns all US states sorted alphabetically
 */
export function getUSStates(): USState[] {
  return [...US_STATES].sort((a, b) => a.name.localeCompare(b.name));
}

/**
 * Returns all cities for a given US state code
 */
export function getCitiesForState(stateCode: string): string[] {
  if (!stateCode) return [];
  const upper = stateCode.trim().toUpperCase();
  const cities = US_CITIES_BY_STATE[upper];
  if (!cities) return [];
  return [...cities].sort((a, b) => a.localeCompare(b));
}

/**
 * Checks if a state code is valid
 */
export function isValidUSStateCode(stateCode: string): boolean {
  if (!stateCode) return false;
  return US_STATES.some((s) => s.code.toUpperCase() === stateCode.trim().toUpperCase());
}
